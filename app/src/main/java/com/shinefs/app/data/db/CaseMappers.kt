package com.shinefs.app.data.db

import com.shinefs.app.data.DivinationCase

fun DivinationCase.toEntity() = DivinationCaseEntity(
    id = id, timestamp = timestamp, sceneId = sceneId, sceneName = sceneName,
    azimuth = azimuth, facingMountain = facingMountain, sittingMountain = sittingMountain,
    facingTrigram = facingTrigram, facingElement = facingElement, stability = stability,
    ruleId = ruleId, ruleDisplayName = ruleDisplayName,
    rulesVersion = rulesVersion, interpretationVersion = interpretationVersion,
    upperTrigram = upperTrigram, lowerTrigram = lowerTrigram,
    originalHexagramOrder = originalHexagramOrder, originalHexagramName = originalHexagramName,
    changingLine = changingLine, changedHexagramOrder = changedHexagramOrder,
    changedHexagramName = changedHexagramName,
    castMode = castMode ?: DivinationCase.CAST_MODE_TIME,
    zoneId = zoneId ?: "Asia/Shanghai",
    calendarVersion = calendarVersion ?: "",
    ruleVersion = ruleVersion ?: "",
    classicCorpusVersion = classicCorpusVersion ?: "",
    dayBoundaryPolicy = dayBoundaryPolicy ?: "CIVIL_MIDNIGHT",
    leapMonthPolicy = leapMonthPolicy ?: "SAME_MONTH_NUMBER",
    northReference = northReference ?: "MAGNETIC",
    rawAzimuth = rawAzimuth, smoothedAzimuth = smoothedAzimuth,
    lunarYear = lunarYear ?: 0, lunarMonth = lunarMonth ?: 0, lunarDay = lunarDay ?: 0,
    leapMonthFlag = leapMonthFlag ?: false,
    yearBranch = yearBranch ?: "", hourBranch = hourBranch ?: "",
    yearBranchNumber = yearBranchNumber ?: 0, lunarMonthNumber = lunarMonthNumber ?: 0,
    lunarDayNumber = lunarDayNumber ?: 0, hourBranchNumber = hourBranchNumber ?: 0,
    nuclearHexagramOrder = nuclearHexagramOrder ?: 0,
    nuclearHexagramName = nuclearHexagramName ?: "",
    tiTrigram = tiTrigram ?: "", yongTrigram = yongTrigram ?: "",
    elementRelation = elementRelation ?: "", seasonalQi = seasonalQi ?: "",
    solarTerm = solarTerm ?: "",
    calculationTrace = calculationTrace, reportText = reportText,
    legacyFixture = legacyFixture,
    houseAuditId = houseAuditId, favorite = favorite, note = note,
)

